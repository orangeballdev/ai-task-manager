import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";

const fileSelect = {
  id: true,
  name: true,
  isFolder: true,
  mimeType: true,
  size: true,
  taskId: true,
  task: { select: { id: true, title: true } },
  parentId: true,
  protected: true,
  createdAt: true,
  updatedAt: true,
} as const;

async function breadcrumbsFor(parentId: string | null) {
  const trail: { id: string; name: string }[] = [];
  let current = parentId;
  while (current) {
    const folder: { id: string; name: string; parentId: string | null } | null = await prisma.file.findUnique({
      where: { id: current },
      select: { id: true, name: true, parentId: true },
    });
    if (!folder) break;
    trail.unshift({ id: folder.id, name: folder.name });
    current = folder.parentId;
  }
  return trail;
}

// GET /api/files?parentId=<id>            -> contents of a folder (root if omitted)
// GET /api/files?q=<query>                -> flat search across all files by name/content
// GET /api/files?taskId=<id>               -> flat list of files generated by a single task only
export async function GET(req: NextRequest) {
  const url = new URL(req.url);
  const q = url.searchParams.get("q")?.trim();
  const taskId = url.searchParams.get("taskId")?.trim();

  if (taskId) {
    const entries = await prisma.file.findMany({
      where: { taskId, isFolder: false },
      orderBy: { createdAt: "asc" },
      select: fileSelect,
    });
    return NextResponse.json({ entries });
  }

  if (q) {
    const matches = await prisma.file.findMany({
      where: {
        isFolder: false,
        OR: [
          { name: { contains: q } },
          { content: { contains: q } },
        ],
      },
      orderBy: { updatedAt: "desc" },
      select: { ...fileSelect, content: true },
    });
    return NextResponse.json({ entries: matches });
  }

  const parentId = url.searchParams.get("parentId") || null;
  if (parentId) {
    const parent = await prisma.file.findUnique({ where: { id: parentId } });
    if (!parent || !parent.isFolder) {
      return NextResponse.json({ error: "Folder not found" }, { status: 404 });
    }
  }

  const entries = await prisma.file.findMany({
    where: { parentId },
    orderBy: [{ isFolder: "desc" }, { name: "asc" }],
    select: fileSelect,
  });
  const breadcrumbs = await breadcrumbsFor(parentId);
  return NextResponse.json({ entries, breadcrumbs, parentId });
}

// POST /api/files — create a folder
export async function POST(req: NextRequest) {
  const { name, parentId } = await req.json() as { name: string; parentId?: string | null };
  if (!name || typeof name !== "string" || !name.trim()) {
    return NextResponse.json({ error: "Folder name is required" }, { status: 400 });
  }

  if (parentId) {
    const parent = await prisma.file.findUnique({ where: { id: parentId } });
    if (!parent || !parent.isFolder) {
      return NextResponse.json({ error: "Parent folder not found" }, { status: 404 });
    }
  }

  const existing = await prisma.file.findFirst({
    where: { parentId: parentId ?? null, name: name.trim() },
  });
  if (existing) {
    return NextResponse.json({ error: "An item with that name already exists here" }, { status: 409 });
  }

  const folder = await prisma.file.create({
    data: { name: name.trim(), isFolder: true, parentId: parentId ?? null },
    select: fileSelect,
  });
  return NextResponse.json(folder);
}
