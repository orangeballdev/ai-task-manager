/**
 * The "Changes summary" the worker stores on `Task.prSummary` after a push.
 *
 * It used to always be headed "# PR: <title>", even for tasks that only pushed to a
 * branch (agent branch, target branch or main) and never opened a pull request. The
 * heading now says "Branch:" for those, and `displayChangesSummary()` rewrites the old
 * wording on rows written before the fix.
 *
 * Pure (no I/O) so it can be unit-tested and used from server components.
 */

export function buildChangesSummary(taskTitle: string, branch: string, isPR: boolean): string {
  if (isPR) {
    return `# PR: ${taskTitle}\n\nBranch: \`${branch}\`\n\nThis PR was generated by Claude Task Manager.\n\n## Changes\n\nSee commit history for details.\n`;
  }
  return `# Branch: ${taskTitle}\n\nBranch: \`${branch}\`\n\nThese changes were pushed by Claude Task Manager.\n\n## Changes\n\nSee commit history for details.\n`;
}

/**
 * Summary text to show for a task. When the task has no PR, a legacy "# PR: …" heading
 * (and the "This PR was generated…" line that came with it) is reworded as a branch push.
 */
export function displayChangesSummary(summary: string | null | undefined, hasPR: boolean): string | null {
  if (!summary) return null;
  if (hasPR) return summary;
  return summary
    .replace(/^# PR: /, "# Branch: ")
    .replace("This PR was generated by Claude Task Manager.", "These changes were pushed by Claude Task Manager.");
}
